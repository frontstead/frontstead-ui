import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

import { compileDefaultThemeCss, compileThemeCss, defineTheme } from "../src/theme";

test("theme output is deterministic and contains light and dark tokens", () => {
  const input = { palette: { primary: "#065f46" }, radius: "8px" } as const;
  const first = compileThemeCss(input);

  assert.equal(first, compileThemeCss(input));
  assert.match(first, /^:root \{/);
  assert.match(first, /--radius: 8px;/);
  assert.match(first, /\n\n\.dark \{/);
  assert.match(first, /--primary-foreground:/);
});

test("rejects invalid colors and unsafe or unsupported radii", () => {
  for (const primary of ["red", "#12", "#12345g", "oklch(1 0 0)"]) {
    assert.throws(() => compileThemeCss({ palette: { primary } }), /expected a hex color/);
  }

  for (const radius of ["-1px", "1%", "1vh", "0; } body { color: red", "url(x)"]) {
    assert.throws(
      () => compileThemeCss({ palette: { primary: "#065f46" }, radius }),
      /expected 0 or a non-negative px, rem, or em length/,
    );
  }
});

test("supports minimal configs and applies optional palette fields", () => {
  const minimal = defineTheme({ palette: { primary: "#065f46" } });
  const minimalCss = compileThemeCss(minimal);
  const expandedCss = compileThemeCss({
    palette: {
      primary: "#065f46",
      accent: "#2563eb",
      ring: "#7c3aed",
      background: "#ffffff",
      foreground: "#111827",
      destructive: "#dc2626",
      success: "#16a34a",
      warning: "#d97706",
    },
  });

  assert.match(minimalCss, /--radius: 0.375rem;/);
  assert.notEqual(expandedCss, minimalCss);
  assert.match(expandedCss, /--background: oklch\(/);
  assert.match(expandedCss, /--success: oklch\(/);
});

test("checked-in default CSS exactly matches canonical theme defaults", async () => {
  const palette = await readFile(new URL("../palette.css", import.meta.url), "utf8");
  const banner = "/* Generated by `npm run palette:generate`. Do not edit directly. */\n\n";
  assert.equal(palette, banner + compileDefaultThemeCss());
});
