import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

import { compileDefaultThemeCss } from "../src/theme";

const output = new URL("../palette.css", import.meta.url);
const banner = "/* Generated by `npm run palette:generate`. Do not edit directly. */\n\n";
const expected = banner + compileDefaultThemeCss();

if (process.argv.includes("--check")) {
  const actual = await readFile(output, "utf8");
  assert.equal(
    actual,
    expected,
    "palette.css differs from the canonical defaults in src/theme.ts; run npm run palette:generate",
  );
} else {
  await writeFile(output, expected);
}
